void HTRIM_FAULT_HANDLER(void) {
	STATE = STATE_FAULT;

	GPIOA->BSRR = (1U << (10 + 16) ); 	// Disable Phase 1
	GPIOC->BSRR = (1U << (9 + 16) ); 	// Disable Phase 2

	LQR_FaultStop();

	GPIOC->BSRR = (1U << (0 + 16) ); // LED_IDLE set to Low
	GPIOC->BSRR = (1U << (1 + 16) ); // LED_RUN set to Low
	GPIOC->BSRR = (1U << 2); // set to High
}

void HAL_HRTIM_Fault1Callback(HRTIM_HandleTypeDef *hhrtim){ HTRIM_FAULT_HANDLER(); }
void HAL_HRTIM_Fault2Callback(HRTIM_HandleTypeDef *hhrtim) { HTRIM_FAULT_HANDLER(); }
void HAL_HRTIM_Fault6Callback(HRTIM_HandleTypeDef *hhrtim) { HTRIM_FAULT_HANDLER(); }
void HAL_HRTIM_SystemFaultCallback(HRTIM_HandleTypeDef *hhrtim) { HTRIM_FAULT_HANDLER(); }


// CHECK INPUT VOLTAGE
uint8_t INPUT_PWR_GOOD() {

	ADC_VIN_raw = ADC4->DR;

	if (ADC_VIN_raw  >= VIN_MIN_THRESHOLD)
	{
		GPIOC->BSRR = (1U << (3 + 16)); // LED_USER = Low
		return 1;
	}
	else {
		GPIOC->BSRR = (1U << (3)); // LED_USER = High
		return 0;
	}
}

void SYSTEM_ENABLE() {
	if (INPUT_PWR_GOOD() == 0 || STATE == STATE_FAULT) {
		HTRIM_FAULT_HANDLER();
	} else {
		GPIOA->BSRR = (1U << (10 + 0) ); 	// Enable Phase 1
		GPIOC->BSRR = (1U << (9 + 0) ); 	// Enable Phase 2

		GPIOC->BSRR = (1U << (0 + 16) ); 	// LED_IDLE = Low
		GPIOC->BSRR = (1U << 1); 			// LED_RUN = High
		GPIOC->BSRR = (1U << (2 + 16) ); 	// Falut_LED = Low

		STATE = STATE_RUN;
		LQR_Init();
	}
}

void SYSTEM_FORCE_ENABLE() {

//		GPIOA->BSRR = (1U << (10 + 0) ); 	// Enable Phase 1
//		GPIOC->BSRR = (1U << (9 + 0) ); 	// Enable Phase 2

		GPIOC->BSRR = (1U << (0 + 16) ); 	// LED_IDLE = Low
		GPIOC->BSRR = (1U << 1); 			// LED_RUN = High
		GPIOC->BSRR = (1U << (2 + 16) ); 	// Falut_LED = Low

		STATE = STATE_RUN;
		LQR_Init();

}

void SYSTEM_DISABLE() {
	if (STATE == STATE_FAULT) return;

	GPIOA->BSRR = (1U << (10 + 16) ); 	// Disable Phase 1
	GPIOC->BSRR = (1U << (9 + 16) ); 	// Disable Phase 2

	LQR_Stop();
	STATE = STATE_IDLE;

	GPIOC->BSRR = (1U << (1 + 16) ); 	// LED_RUN = Low

	// Soft Fault
	if(INPUT_PWR_GOOD() == 1) {
		GPIOC->BSRR = (1U << 0); 		// LED_IDLE = High
		GPIOC->BSRR = (1U << (2 + 16) );// Falut_LED = Low
	} else {
		GPIOC->BSRR = (1U << (0 + 16)); // LED_IDLE = Low
		GPIOC->BSRR = (1U << (2)); 		// Falut_LED = High
	}


}

// SW EXINT CONTROL
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin) {

	if(GPIO_Pin == SW1_USER_Pin) {
		if(HAL_GPIO_ReadPin(SW1_USER_GPIO_Port, SW1_USER_Pin)) {
			SYSTEM_ENABLE();
		} else {
			SYSTEM_DISABLE();
		}
	}

}

void SYSTEM_PowerOn(void) {

	HAL_NVIC_DisableIRQ(EXTI15_10_IRQn);

	for (uint8_t i=0; i<3; i++) {
		GPIOC->BSRR = (1U << 2);
		HAL_Delay(200);
		GPIOC->BSRR = (1U << (2 + 16));
		HAL_Delay(800);
	}

	__HAL_GPIO_EXTI_CLEAR_IT(SW1_USER_Pin); // Clear flag IR
	HAL_NVIC_EnableIRQ(EXTI15_10_IRQn);

	if (HAL_GPIO_ReadPin(SW1_USER_GPIO_Port, SW1_USER_Pin) == GPIO_PIN_SET) {
		SYSTEM_ENABLE();
	}
	else  {
		SYSTEM_DISABLE();
	}
}

